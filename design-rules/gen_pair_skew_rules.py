#!/usr/bin/env python3
"""Emit one KiCad 7-compatible intra-pair skew rule per differential pair.
Usage:  python3 gen_pair_skew_rules.py board.kicad_pcb [--max 0.127] [--classes PCIe_85,REFCLK_100] >> board.kicad_dru
Pairs are recognised the KiCad way: names ending in _P/_N, +/-, or P/N (e.g. PET0_P / PET0_N, REFCLK+ / REFCLK-)."""
import sys, re, argparse, pcbnew
ap=argparse.ArgumentParser(); ap.add_argument("board"); ap.add_argument("--max",default="0.127")
ap.add_argument("--classes",default="PCIe_85,REFCLK_100"); a=ap.parse_args()
classes=set(a.classes.split(","))
b=pcbnew.LoadBoard(a.board)
nets={n.GetNetname():n.GetNetClassName() for n in b.GetNetsByName().values()}
pairs={}
for name,cls in nets.items():
    if cls.split(",")[0] not in classes: continue
    m=re.match(r"^(.*?)(_P|_N|\+|-|P|N)$",name)
    if not m: continue
    base,suf=m.groups(); pol='P' if suf in ('_P','+','P') else 'N'
    pairs.setdefault(base,{})[pol]=name
print("# --- generated by gen_pair_skew_rules.py: intra-pair skew <= %s mm ---"%a.max)
for base,pn in sorted(pairs.items()):
    if 'P' in pn and 'N' in pn:
        print('(rule "skew %s"\n    (condition "A.NetName == \'%s\' || A.NetName == \'%s\'")\n    (constraint skew (max %smm)))'%(base,pn['P'],pn['N'],a.max))
